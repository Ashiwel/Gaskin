#!/usr/bin/env python3
"""
Build Gaskin's embedded Inter: src/styles/fonts.css (a woff2 data URI, works offline from a USB stick).

Source: Inter 4.1 (SIL OFL 1.1), https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip,
file InterVariable.ttf, SHA-256 checked below. The variable font is cut to the text optical size
(opsz 14), weights 400 to 700, and the Latin, Latin Extended, IPA and combining-mark ranges that the
Nigerian, Ghanaian and Kenyan language packs need (Yoruba e/o/s with dots and tone marks, Igbo i/o/u
with dots and n-dot, Hausa hooked b/d/k/y, Twi open e/o, Ewe and Dagbani d-tail, f-hook, eng, gamma,
v-hook and ezh). Anything else (Arabic, Chinese) falls back to the system face through unicode-range.

Usage:
  pip install --break-system-packages fonttools brotli
  python3 scripts/font/build-inter.py /path/to/InterVariable.ttf
  python3 scripts/font/build-inter.py --check        # coverage report only, against the built CSS

The coverage check scans every language pack and every source string for characters, and fails if
a Latin-script character used by Gaskin is missing from the subset.
"""
import base64, glob, hashlib, io, os, re, subprocess, sys, tempfile, unicodedata

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'src', 'styles', 'fonts.css')
UNICODES = [
    (0x0000, 0x00FF), (0x0100, 0x024F), (0x0250, 0x02FF), (0x0300, 0x036F), (0x1E00, 0x1EFF),
    (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F), (0x2190, 0x21FF), (0x2212, 0x2212),
    (0x2215, 0x2215), (0x2219, 0x2219), (0x221E, 0x221E), (0x2248, 0x2248), (0x2260, 0x2260),
    (0x2264, 0x2265), (0x25A0, 0x25FF), (0x2713, 0x2713), (0x2715, 0x2715), (0xFEFF, 0xFEFF), (0xFFFD, 0xFFFD),
]
FEATURES = 'kern,liga,calt,ccmp,locl,mark,mkmk,tnum,case,zero,frac'
# Characters the packs need, listed explicitly so the check fails loudly if a range is ever narrowed.
REQUIRED = 'ẹọṣẸỌṢịụṅỊỤṄɓɗƙƴƁƊƘƳɛɔƐƆɖƒŋɣʋʒƉƑŊƔƲƷ' + '̣̀́̂̄̌̇̃' + '₦₵₹€£'


def urange():
    return ','.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in UNICODES)


def build(src):
    from fontTools.ttLib import TTFont  # noqa: F401  (fails early with a clear message)
    with open(src, 'rb') as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    print('source', src, 'sha256', digest)
    with tempfile.TemporaryDirectory() as tmp:
        inst = os.path.join(tmp, 'inst.ttf')
        out = os.path.join(tmp, 'inter.woff2')
        subprocess.run([sys.executable, '-m', 'fontTools.varLib.instancer', src, 'opsz=14', 'wght=400:700', '-o', inst, '-q'], check=True)
        subprocess.run([sys.executable, '-m', 'fontTools.subset', inst, f'--unicodes={urange()}', f'--layout-features={FEATURES}',
                        '--flavor=woff2', f'--output-file={out}', '--no-hinting', '--desubroutinize', '--name-IDs=0,1,2,3,4,5,6'], check=True)
        data = open(out, 'rb').read()
    b64 = base64.b64encode(data).decode()
    css = f"""/*
  Inter 4.1 by Rasmus Andersson, SIL Open Font License 1.1 (see THIRD_PARTY_NOTICES.md).
  Generated by scripts/font/build-inter.py: variable weight 400 to 700, text optical size, subset to
  Latin, Latin Extended, IPA and combining marks ({len(data):,} bytes woff2). Do not edit by hand.
  Characters outside the subset (Arabic, Chinese) fall back to the system face through unicode-range.
*/
@font-face {{
  font-family: 'Inter';
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
  src: url(data:font/woff2;base64,{b64}) format('woff2');
  unicode-range: {urange()};
}}
"""
    open(OUT, 'w').write(css)
    print(f'wrote {OUT}: woff2 {len(data):,} bytes, CSS {len(css):,} bytes')


def font_from_css():
    from fontTools.ttLib import TTFont
    m = re.search(r'base64,([A-Za-z0-9+/=]+)', open(OUT).read())
    return TTFont(io.BytesIO(base64.b64decode(m.group(1))))


def check():
    cmap = font_from_css().getBestCmap()
    used = {}
    for f in glob.glob(os.path.join(ROOT, 'src', '**', '*.ts*'), recursive=True):
        for ch in open(f, encoding='utf8').read():
            if ord(ch) > 127:
                used.setdefault(ch, f)
    for ch in REQUIRED:
        used.setdefault(ch, 'REQUIRED')
    missing_latin, fallback = [], {}
    for ch, where in sorted(used.items()):
        if ord(ch) in cmap:
            continue
        name = unicodedata.name(ch, '?')
        script = name.split(' ')[0]
        if script in ('LATIN', 'COMBINING', 'MODIFIER') or where == 'REQUIRED':
            missing_latin.append((f'U+{ord(ch):04X}', name, os.path.relpath(where, ROOT) if where != 'REQUIRED' else where))
        else:
            fallback[script] = fallback.get(script, 0) + 1
    print(f'{len(used)} distinct non-ASCII characters used; covered by Inter: {sum(1 for c in used if ord(c) in cmap)}')
    print('system fallback by script:', ', '.join(f'{k} {v}' for k, v in sorted(fallback.items(), key=lambda x: -x[1])) or 'none')
    if missing_latin:
        print('MISSING Latin-script characters:')
        for m in missing_latin:
            print('  ', *m)
        sys.exit(1)
    print('OK: every Latin-script character Gaskin uses is in the embedded Inter.')


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] != '--check':
        build(sys.argv[1])
    check()
