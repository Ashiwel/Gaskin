export function findPractice(id: string): TraditionalPractice | undefined {
  const key = id.trim().toLowerCase().replace(/[\s-]+/g, '_');
  return TRADITIONAL_PRACTICES.find((p) => p.id === key) ?? TRADITIONAL_PRACTICES.find((p) => p.id === ALIASES[key]);
}
