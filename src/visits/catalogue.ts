/** Fundal height should be within about 3 cm of the gestational week after 24 weeks. */
function fundalInput(c: VisitCtx): ItemInput {
  const w = ga(c);
  const twins = c.flags.twins;
  return {
    kind: 'number',
    unit: 'cm',
    min: 10,
    max: 50,
    step: 1,
    normal: `About ${w} cm at ${w} weeks (±3 cm)`,
    bands: [
      { below: w - 3, finding: refer(`Fundal height more than 3 cm below ${w} weeks (small for dates)`, 'routine', 'Check dates. Refer for an ultrasound and growth review this week; ask about fetal movements.') },
      ...(twins ? [] : [{ atLeast: w + 4, finding: refer(`Fundal height more than 3 cm above ${w} weeks (large for dates)`, 'routine', 'Check dates. Refer for an ultrasound (twins, excess fluid, large baby, diabetes).') }]),
    ],
  };
}

/** Newborn weight: birth-weight bands at birth; weight loss over 10% in the first two weeks. */
function babyWeightInput(c: VisitCtx): ItemInput {
  const bw = c.child?.birthWeightKg;
  const days = c.childAgeDays ?? 0;
  if (isBirth(c) || !bw) {
    return {
      kind: 'number',
      unit: 'kg',
      min: 0.5,
      max: 6,
      step: 0.05,
      normal: '2.5 kg or more',
      bands: [
        { below: 1.5, finding: refer('Very low birth weight (under 1.5 kg)', 'urgent', 'Refer to {hospital} today for special newborn care. Start skin-to-skin (KMC) on the way; keep warm and breastfeed or give expressed milk.') },
        { below: 2.5, finding: treat('Low birth weight (under 2.5 kg)', 'Start kangaroo mother care now: skin-to-skin for as many hours as possible, breastfeed every 2–3 hours, keep warm. Weigh twice a week. Refer if not feeding or temperature is low.', { textKey: 'baby.skin_to_skin' }) },
      ],
    };
  }
  if (days <= 14) {
    const limit = Math.round(bw * 0.9 * 100) / 100;
    return {
      kind: 'number',
      unit: 'kg',
      min: 0.5,
      max: 8,
      step: 0.05,
      normal: `${limit} kg or more (birth weight ${bw} kg; up to 10% loss is normal in the first week)`,
      bands: [{ below: limit, finding: refer(`Lost more than 10% of birth weight (${bw} kg)`, 'urgent', 'Observe a full breastfeed and correct attachment. Refer to {sameDay} today for feeding assessment.', { textKey: 'bf.more_milk' }) }],
    };
  }
  return { kind: 'number', unit: 'kg', min: 1, max: 20, step: 0.05, normal: 'Plot on the growth chart; the line should rise', bands: [] };
}

function babyTempInput(c: VisitCtx): ItemInput {
  const y = young(c);
  return {
    kind: 'number',
    unit: '°C',
    min: 32,
    max: 42,
    step: 0.1,
    normal: '36.5 to 37.4 °C (armpit)',
    bands: [
      { below: 35.5, finding: refer('Low temperature (below 35.5 °C)', 'emergency', `${NOW} Warm skin-to-skin on the way and keep breastfeeding.`, { symptom: 'baby_cold', textKey: 'alert.newborn_danger' }) },
      { below: 36.5, finding: recheck('Cool (35.5 to 36.4 °C)', 'Warm skin-to-skin with a cap and blanket; recheck in 1 hour. Refer if still below 36.5 °C.', { textKey: 'vt.finding.low_temp' }) },
      y
        ? { atLeast: 37.5, finding: refer('Fever (37.5 °C or more) in a baby under 2 months', 'emergency', `${NOW} Fever is a danger sign at this age (WHO 2024).`, { symptom: 'baby_fever', textKey: 'alert.newborn_danger' }) }
        : { atLeast: 37.5, finding: refer('Fever (37.5 °C or more)', 'urgent', 'Malaria RDT today. Treat a positive RDT under iCCM if trained; otherwise refer to {sameDay} today. Refer now if any danger sign.', { symptom: 'baby_fever', textKey: 'alert.child_fever' }) },
    ],
  };
}

function breathingInput(c: VisitCtx): ItemInput {
  const days = c.childAgeDays ?? 0;
  const limit = days < 60 ? 60 : days < 365 ? 50 : 40;
  return {
    kind: 'number',
    unit: 'breaths/min',
    min: 10,
    max: 120,
    step: 1,
    normal: `Below ${limit} a minute (count a full minute while calm)`,
    bands: [
      days < 60
        ? { atLeast: 60, finding: refer('Fast breathing (60 or more) under 2 months', 'emergency', NOW, { symptom: 'baby_fast_breathing', textKey: 'alert.newborn_danger' }) }
        : { atLeast: limit, finding: refer(`Fast breathing (${limit} or more)`, 'urgent', 'Possible pneumonia. Give oral amoxicillin under iCCM only if trained and authorised; otherwise refer to {sameDay} today. Refer now if chest indrawing or any danger sign.', { symptom: 'baby_fast_breathing' }) },
    ],
  };
}

function jaundiceInput(c: VisitCtx): ItemInput {
  const firstDay = (c.childAgeDays ?? 0) <= 1;
  const early24 = (z: string) =>
    firstDay ? refer(`Yellow in the first 24 hours (${z})`, 'emergency', `${NOW} Jaundice on day 1 is always a danger sign.`, { symptom: 'baby_yellow_skin', textKey: 'alert.newborn_danger' }) : undefined;
  return {
    kind: 'choice',
    options: [
      { value: 'none', label: 'No yellow colour (press the skin on the forehead in daylight)' },
      { value: 'z1', label: 'Zone 1: head and neck only', finding: early24('zone 1') ?? recheck('Mild jaundice, zone 1', 'Breastfeed at least 8 times a day; check again in 1–2 days.', { symptom: 'baby_yellow_skin', textKey: 'vt.jaundice_watch' }) },
      { value: 'z2', label: 'Zone 2: down to the belly button', finding: early24('zone 2') ?? recheck('Jaundice to zone 2', 'Breastfeed often; recheck tomorrow. Refer if it spreads or the baby feeds poorly.', { symptom: 'baby_yellow_skin', textKey: 'vt.jaundice_watch' }) },
      { value: 'z3', label: 'Zone 3: lower belly and thighs', finding: early24('zone 3') ?? refer('Jaundice to zone 3 (thighs)', 'urgent', 'Refer to {hospital} today for a bilirubin check.', { symptom: 'baby_yellow_skin', textKey: 'alert.jaundice' }) },
      { value: 'z4', label: 'Zone 4: arms and lower legs', finding: early24('zone 4') ?? refer('Jaundice to zone 4 (arms and legs)', 'urgent', 'Refer to {hospital} today for a bilirubin check and possible phototherapy.', { symptom: 'baby_yellow_skin', textKey: 'alert.jaundice' }) },
      { value: 'z5', label: 'Zone 5: palms and soles', finding: refer('Yellow palms and soles', 'emergency', `${NOW} Yellow palms or soles at any age is a danger sign (WHO PNC rec. 25).`, { symptom: 'baby_yellow_skin', textKey: 'alert.newborn_danger' }) },
    ],
  };
}

