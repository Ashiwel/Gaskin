/**
 * Guided visit checklists: templates for every contact from preconception to a child's second
 * birthday, and the catalogue of items they draw on.
 *
 * Every item has a stable id, a source, and (for checks) what counts as abnormal and what to do.
 * Where Nigerian CHEW standing orders (NPHCDA 2015) are unclear about a task, the action is "refer".
 * Worker text may use {hospital} and {sameDay}; build.ts fills them from COUNTRY_RULES.
 *
 * Schedules: ANC follows WHO 2016 rec. E.7 (contacts at up to 12, 20, 26, 30, 34, 36, 38, 40 weeks),
 * PNC follows WHO 2022 rec. 44 (24 h, 48–72 h, 7–14 days, 6 weeks), and child visits follow the
 * NPHCDA routine immunisation calendar (6, 10, 14 weeks; 6, 9, 12, 15 months) with growth and
 * development visits at 18 and 24 months. Vaccines due at each visit come from IMMUNISATION_SCHEDULES,
 * so Kenya and Ghana get their own antigens and timings.
 */
import type { IllustrationKey, SymptomCode, VisitEvent } from '../types';
import type { Emit, FindingSpec, ItemInput, VisitCtx, VisitSection } from './types';

