// ---------- Catalogue item shape ----------

type Dyn<T> = T | ((c: VisitCtx) => T);

export interface CatalogueItem {
  id: string;
  section: VisitSection;
  subject: 'mother' | 'baby';
  title: Dyn<string>;
  how?: Dyn<string>;
  why: string;
  sources: string[];
  priority: 1 | 2 | 3 | 4 | 5;
  input: Dyn<ItemInput>;
  emit?: Emit;
  illustration?: IllustrationKey;
  once?: boolean;
  dependsOn?: Dyn<string | undefined>;
  textKey?: Dyn<string>;
  params?: (c: VisitCtx) => Record<string, string | number>;
  /** Does this item belong in this visit for this patient? */
  when: (c: VisitCtx) => boolean;
  /** Return a reason to leave the item out because it is already done */
  skipIf?: (c: VisitCtx) => string | undefined;
  /** Facts that added this item, shown as "because" */
  because?: (c: VisitCtx) => string[];
}

// ---------- Helpers ----------

const refer = (label: string, urgency: FindingSpec['urgency'], todo: string, extra: Partial<FindingSpec> = {}): FindingSpec => ({ label, action: 'refer', urgency, todo, ...extra });
const treat = (label: string, todo: string, extra: Partial<FindingSpec> = {}): FindingSpec => ({ label, action: 'treat', urgency: 'routine', todo, ...extra });
const recheck = (label: string, todo: string, extra: Partial<FindingSpec> = {}): FindingSpec => ({ label, action: 'recheck', urgency: 'routine', todo, ...extra });

const NOW = 'Emergency referral to {hospital} now.';
const TODAY = 'Refer to {sameDay} today.';

const t = (c: VisitCtx) => c.template;
const isAnc = (c: VisitCtx) => t(c).stage === 'pregnancy';
const isBirth = (c: VisitCtx) => t(c).id === 'birth';
const isPnc = (c: VisitCtx) => t(c).stage === 'postpartum' || isBirth(c);
const isChild = (c: VisitCtx) => t(c).stage === 'infant';
const isPrecon = (c: VisitCtx) => t(c).stage === 'preconception';
const anyOf = (...ids: string[]) => (c: VisitCtx) => ids.includes(t(c).id);
const booking = (c: VisitCtx) => isAnc(c) && (t(c).id === 'anc1' || c.ancAttended === 0);
const ga = (c: VisitCtx) => c.ga ?? t(c).gaWeek ?? 0;
const early = (c: VisitCtx) => isPnc(c) && t(c).id !== 'pnc_6wk';
const young = (c: VisitCtx) => (c.childAgeDays ?? 0) < 60;
const ageM = (c: VisitCtx) => (c.childAgeDays ?? 0) / 30.4;
const babyVisit = (c: VisitCtx) => t(c).includesBaby;
const hasBaby = (c: VisitCtx) => !!c.child;

